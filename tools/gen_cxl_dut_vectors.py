#!/usr/bin/env python3
"""Extract CXL.cachemem message vectors from the customer DUT stimulus files.

Source (read-only, never modified):
  $CXL3SW_HOME/top1/ep_stimu.v
  $CXL3SW_HOME/top1/cxl_stimu.v

These are the exact words the customer testbench drives/observes on the CTL
CXL.cachemem app interface, so they are the wire-level docking vectors for the
TLM encoders.  The generated header is included by tb_cxl_dut_docking.
"""
import os
import re
import sys

ROOT = os.environ.get("CXL3SW_HOME", "/mnt/hgfs/g/cxl_sw33")
FILES = [
    ("ep_stimu.v", os.path.join(ROOT, "top1", "ep_stimu.v")),
    ("cxl_stimu.v", os.path.join(ROOT, "top1", "cxl_stimu.v")),
]
# (output name, source signal, declared width)
VECTORS = [
    ("D2H_REQ", "cxl_slv_d2h_req", 79),
    ("D2H_RSP", "cxl_slv_d2h_rsp", 20),
    ("D2H_DATA", "cxl_slv_d2h_data", 593),
    ("S2M_NDR", "cxl_slv_s2m_ndr", 30),
    ("S2M_DRC", "cxl_slv_s2m_drc", 552),
    ("M2S_REQ", "cxl_slv_m2s_req", 87),
]
# Commented-out examples in the customer stimulus are useful as wire-format
# references; they are emitted with the _REF suffix and never treated as the
# active stimulus.
REF_VECTORS = [
    ("H2D_REQ_REF", "cxl_slv_h2d_req", 64),
    ("M2S_REQ_REF", "cxl_slv_m2s_req", 87),
]

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "tb", "tb_cxl_dut_docking", "dut_vectors.h")


def find_vector(path, signal, width):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
    except OSError as exc:
        sys.stderr.write("[gen_cxl_dut_vectors] cannot read %s: %s\n" % (path, exc))
        return None
    pat = re.compile(r"\b%s\s*=\s*%d'h([0-9a-fA-F_]+)" % (re.escape(signal), width))
    for lineno, line in enumerate(lines, 1):
        m = pat.search(line)
        if not m:
            continue
        digits = m.group(1).replace("_", "")
        value = int(digits, 16)
        if value >= (1 << width):
            sys.stderr.write("[gen_cxl_dut_vectors] %s:%d value does not fit %d bits\n"
                             % (path, lineno, width))
            return None
        return value, lineno
    return None


def find_commented_vector(path, signal, width):
    """Find the first nonzero literal of the given width on a line that names
    the signal (used for commented-out reference examples)."""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
    except OSError:
        return None
    pat = re.compile(r"%d'h([0-9a-fA-F_]+)" % width)
    for lineno, line in enumerate(lines, 1):
        if signal not in line:
            continue
        for m in pat.finditer(line):
            value = int(m.group(1).replace("_", ""), 16)
            if value:
                return value, lineno
    return None


def main():
    entries = []
    for name, signal, width in VECTORS:
        found = None
        for fname, path in FILES:
            r = find_vector(path, signal, width)
            if r is not None:
                found = (fname, path, r[0], r[1])
                break
        if found is None:
            sys.stderr.write("[gen_cxl_dut_vectors] missing %s (%d bits)\n"
                             % (signal, width))
            return 1
        fname, path, value, lineno = found
        nbytes = (width + 7) // 8
        raw = value.to_bytes(nbytes, "little")
        entries.append((name, signal, width, fname, lineno, raw))
        print("[gen] %-8s %3d bits  %s:%d" % (name, width, fname, lineno))

    for name, signal, width in REF_VECTORS:
        found = None
        for fname, path in FILES:
            r = find_commented_vector(path, signal, width)
            if r is not None:
                found = (fname, path, r[0], r[1])
                break
        if found is None:
            sys.stderr.write("[gen_cxl_dut_vectors] missing reference %s\n" % signal)
            continue
        fname, path, value, lineno = found
        nbytes = (width + 7) // 8
        raw = value.to_bytes(nbytes, "little")
        entries.append((name, signal, width, fname, lineno, raw))
        print("[gen] %-8s %3d bits  %s:%d (commented reference)"
              % (name, width, fname, lineno))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/gen_cxl_dut_vectors.py -- do not edit.\n")
        f.write("// Exact CXL.cachemem words from the customer DUT stimulus.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("struct DutVector {\n")
        f.write("    const char* name;\n")
        f.write("    const char* signal;\n")
        f.write("    const char* source;\n")
        f.write("    int line;\n")
        f.write("    int bits;\n")
        f.write("    std::uint8_t bytes[80];\n")
        f.write("};\n\n")
        f.write("static const DutVector kDutVectors[] = {\n")
        for name, signal, width, fname, lineno, raw in entries:
            arr = ",".join("0x%02x" % b for b in raw)
            f.write('    {"%s", "%s", "%s", %d, %d, {%s}},\n'
                    % (name, signal, fname, lineno, width, arr))
        f.write("};\n")
        f.write("static const int kDutVectorCount = %d;\n" % len(entries))
    print("[gen] wrote %s (%d vectors)" % (OUT, len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
